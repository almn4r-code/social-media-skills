// Deploys straight to Cloudflare Pages through the REST API:
//   1. inline public/ into src/assets.generated.js
//   2. bundle src/worker.js into dist/_worker.js (esbuild, from wrangler's deps)
//   3. wrap it as a "_worker.bundle" and write dist/ for the upload
//   4. sync D1 binding + vars from wrangler.toml onto the Pages project
//   5. create the deployment
// Needs CLOUDFLARE_ACCOUNT_ID and CLOUDFLARE_API_TOKEN (Pages Edit).
// Usage: node scripts/deploy.mjs [branch]   (default: main)
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from 'node:fs';
import { join, relative } from 'node:path';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';

const root = new URL('..', import.meta.url).pathname;
const require = createRequire(join(root, 'node_modules/wrangler/package.json'));
const esbuild = require('esbuild');
const { ACCOUNT = process.env.CLOUDFLARE_ACCOUNT_ID, TOKEN = process.env.CLOUDFLARE_API_TOKEN } = {};
if (!ACCOUNT || !TOKEN) throw new Error('Set CLOUDFLARE_ACCOUNT_ID and CLOUDFLARE_API_TOKEN');
const branch = process.argv[2] || 'main';

// --- config from wrangler.toml (tiny parser for the keys we use) ---
const toml = readFileSync(join(root, 'wrangler.toml'), 'utf8');
const val = (key, scope = toml) => (scope.match(new RegExp(`^${key}\\s*=\\s*"([^"]*)"`, 'm')) || [])[1];
const project = val('name');
const compatibilityDate = val('compatibility_date');
const varsBlock = (toml.split('[vars]')[1] || '').split(/^\[/m)[0];
const vars = Object.fromEntries([...varsBlock.matchAll(/^([A-Z_]+)\s*=\s*"([^"]*)"/gm)].map((m) => [m[1], m[2]]));
const dbId = val('database_id');

// --- 1. inline static assets ---
const files = {};
(function walk(dir) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else files['/' + relative(join(root, 'public'), p)] = readFileSync(p, 'utf8');
  }
})(join(root, 'public'));
writeFileSync(join(root, 'src/assets.generated.js'), `// generated by scripts/deploy.mjs\nexport const ASSETS = ${JSON.stringify(files)};\n`);

// --- 2. bundle ---
mkdirSync(join(root, 'dist'), { recursive: true });
await esbuild.build({
  entryPoints: [join(root, 'src/worker.js')], bundle: true, format: 'esm', target: 'es2022',
  outfile: join(root, 'dist/_worker.js'), minify: true, logLevel: 'warning',
});

// --- 3. _worker.bundle (multipart: metadata + module) ---
const fd = new FormData();
fd.set('metadata', JSON.stringify({ main_module: '_worker.js' }));
fd.set('_worker.js', new File([readFileSync(join(root, 'dist/_worker.js'))], '_worker.js', { type: 'application/javascript+module' }));
writeFileSync(join(root, 'dist/_worker.bundle'), Buffer.from(await new Response(fd).arrayBuffer()));

// --- 4/5. API calls via curl (honours the HTTPS proxy and CA bundle) ---
const api = `https://api.cloudflare.com/client/v4/accounts/${ACCOUNT}/pages/projects/${project}`;
function curl(args) {
  const out = execFileSync('curl', ['-sS', '-H', `Authorization: Bearer ${TOKEN}`, ...args], { encoding: 'utf8' });
  const res = JSON.parse(out);
  if (!res.success) throw new Error(JSON.stringify(res.errors));
  return res.result;
}
const envConfig = {
  compatibility_date: compatibilityDate,
  d1_databases: { DB: { id: dbId } },
  env_vars: Object.fromEntries(Object.entries(vars).map(([k, v]) => [k, { type: 'plain_text', value: v }])),
};
curl(['-X', 'PATCH', api, '-H', 'content-type: application/json', '--data',
  JSON.stringify({ deployment_configs: { production: envConfig, preview: envConfig } })]);
const dep = curl(['-X', 'POST', `${api}/deployments`, '-F', 'manifest={}', '-F', `branch=${branch}`,
  '-F', `_worker.bundle=@${join(root, 'dist/_worker.bundle')};filename=_worker.bundle`]);
console.log(`✨ Deployed ${dep.id} → ${dep.url}`);
